// Clave de concepto: mayúsculas, sin tildes ni signos y sin números sueltos.
// "To Veronica Concepción Perez" y "To Veronica Concepcion Perez" dan la misma clave.
// Los caracteres rotos de Ventajón ("Ca￱on") quedan como espacio: "CA ON COSMO STORE".
export const conceptKey = (description: string) =>
  String(description)
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, " ")
    .replace(/\b\d+\b/g, " ")
    .replace(/\s+/g, " ")
    .trim()

const words = (list: string) => new RegExp(`\\b(?:${list})\\b`)

// En orden: la primera que coincide gana (restauración antes que tiendas, para "Restaurante IKEA")
