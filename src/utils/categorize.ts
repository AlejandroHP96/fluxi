// Categoría de un movimiento: primero tus reglas (concepto -> categoría), luego las de serie
export function categorize(description: string, isIncome: boolean, userRules: Record<string, string> = {}): string {
  if (isIncome) return "Ingresos"
  const key = conceptKey(description)
  if (userRules[key]) return userRules[key]
  for (const [re, category] of RULES) if (re.test(key)) return category
  return "Otro"
}
